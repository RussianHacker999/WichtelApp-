package com.example.wichtly.ui.theme

import androidx.compose.ui.unit.dp

/**
 * The only spacing values the screens use. Keeping them in one place is what makes
 * every screen line up the same way.
 */
object Spacing {
    val xs = 4.dp
    val s = 8.dp
    val m = 12.dp
    val l = 16.dp
    val xl = 24.dp
    val xxl = 32.dp

    /** Left/right padding of every screen. */
    val screen = 16.dp

    /** Gap between two sections of a screen. */
    val section = 24.dp

    /** Gap between two cards in a list. */
    val cardGap = 12.dp

    /** Inner padding of a card. */
    val cardPadding = 16.dp
}
